import assert from "node:assert/strict";
import test from "node:test";
import { app } from "../../src/app.js";
import { prisma } from "../../src/database/prisma.js";
import jwt from "jsonwebtoken";

test("HTTP authentication, access control, validation and commerce", async () => {
    assert.equal(process.env.NODE_ENV, "test");
    const server = app.listen(0, "127.0.0.1");
    await new Promise((resolve) => server.once("listening", resolve));
    const base = `http://127.0.0.1:${server.address().port}/api`;
    async function request(path, { method = "GET", body, token, raw } = {}) {
        const headers = {};
        if (body !== undefined || raw !== undefined) headers["Content-Type"] = "application/json";
        if (token) headers.Authorization = `Bearer ${token}`;
        const response = await fetch(base + path, { method, headers, body: raw ?? (body === undefined ? undefined : JSON.stringify(body)) });
        return { status: response.status, json: await response.json() };
    }
    try {
        const preflight = await fetch(base + "/retail/cart", { method: "OPTIONS", headers: { Origin: "http://127.0.0.1:5189", "Access-Control-Request-Method": "GET", "Access-Control-Request-Headers": "authorization" } });
        assert.equal(preflight.headers.get("access-control-allow-origin"), "http://127.0.0.1:5189");
        const denied = await fetch(base + "/products", { headers: { Origin: "https://untrusted.example" } });
        assert.equal(denied.headers.get("access-control-allow-origin"), null);
        assert.equal((await request("/products")).status, 200);
        assert.equal((await fetch(base.slice(0, -4))).status, 200);
        assert.equal((await request("/traceability/public/recent")).json.data.length, 4);
        const sorted = (await request("/products?sort=asc&limit=100")).json.data;
        assert.deepEqual(sorted.map(product => product.price), sorted.map(product => product.price)
            .sort((a, b) => (a === null ? Infinity : Number(a)) - (b === null ? Infinity : Number(b))));
        const search = (q, options = {}) => request("/products?" + new URLSearchParams({ q, ...options }));
        const accentedSearch = await search("Nâu Đất");
        assert.equal(accentedSearch.status, 200);
        assert.ok(accentedSearch.json.data.some(product => product.name.includes("Nâu Đất")));
        for (const query of ["Nau Dat", "NÂU ĐẤT", "Nâu Đất".normalize("NFD")]) {
            assert.deepEqual((await search(query)).json, accentedSearch.json);
        }
        const found = accentedSearch.json.data[0];
        const filters = { category: found.category.slug, sort: "desc" };
        const filtered = await search("Vai to tam", filters);
        assert.equal(filtered.status, 200);
        assert.ok(filtered.json.data.length > 1);
        assert.ok(filtered.json.data.every(product => product.category.slug === filters.category));
        const prices = filtered.json.data.filter(product => product.price !== null).map(product => Number(product.price));
        assert.deepEqual(prices, [...prices].sort((a, b) => b - a));
        for (const page of [1, 2]) {
            const result = await search("Vải tơ tằm", { ...filters, page, limit: 1 });
            assert.deepEqual(result.json.data, filtered.json.data.slice(page - 1, page));
        }
        const fromWorkshop = await search("Xuong Soi Moc", { ...filters, artisanId: found.artisan.id });
        assert.ok(fromWorkshop.json.data.some(product => product.id === found.id));
        assert.ok(fromWorkshop.json.data.every(product => product.artisan.id === found.artisan.id));
        assert.deepEqual((await search("%")).json.data, []);
        assert.equal((await request("/artisans?visitorsOnly=bad")).status, 400);
        assert.equal((await request("/retail/cart")).status, 401);
        assert.equal((await request("/auth/login", { method: "POST", raw: "{" })).status, 400);
        const credentials = { email: "api-test@example.test", password: "Secure-test-password-123", fullName: "API buyer" };
        assert.equal((await request("/auth/register", { method: "POST", body: { ...credentials, role: "ADMIN" } })).status, 400);
        assert.equal((await request("/auth/register", { method: "POST", body: credentials })).status, 201);
        assert.equal((await request("/auth/register", { method: "POST", body: credentials })).status, 409);
        assert.equal((await request("/auth/login", { method: "POST", body: { email: credentials.email, password: "wrong" } })).status, 401);
        const login = await request("/auth/login", { method: "POST", body: { email: credentials.email, password: credentials.password } });
        assert.equal(login.status, 200);
        const token = login.json.data.accessToken;
        const expired = jwt.sign({}, process.env.JWT_SECRET, { algorithm: "HS256", subject: "00000000-0000-4000-8000-000000000000", issuer: "vcraft", audience: "vcraft-api", expiresIn: -1 });
        assert.equal((await request("/auth/me", { token: expired })).status, 401);
        const me = await request("/auth/me", { token });
        assert.equal(me.json.data.role, "BUYER");
        assert.equal(Object.hasOwn(me.json.data, "passwordHash"), false);
        const second = { ...credentials, email: "api-test-other@example.test" };
        assert.equal((await request("/auth/register", { method: "POST", body: second })).status, 201);
        const otherLogin = await request("/auth/login", { method: "POST", body: { email: second.email, password: second.password } });
        const otherToken = otherLogin.json.data.accessToken;
        assert.equal((await request("/wholesale/assignments", { token })).status, 403);
        assert.equal((await request("/wholesale/quotes", { method: "POST", token, body: { title: "Order", specifications: "Silk", targetQuantity: 5, deadline: "2099-01-01", userId: "00000000-0000-0000-0000-000000000000" } })).status, 400);
        const quote = await request("/wholesale/quotes", { method: "POST", token, body: { title: "Order", specifications: "Silk", targetQuantity: 5, deadline: "2099-01-01" } });
        assert.equal(quote.status, 201);
        assert.equal(quote.json.data.buyerId, me.json.data.id);
        assert.equal((await request(`/wholesale/quotes/${quote.json.data.id}`, { token: otherToken })).status, 404);
        assert.equal((await request(`/wholesale/quotes/${quote.json.data.id}/send`, { method: "POST", token: otherToken })).status, 409);
        assert.equal((await request(`/wholesale/quotes/${quote.json.data.id}/send`, { method: "POST", token })).status, 200);
        const product = await prisma.product.findUniqueOrThrow({ where: { slug: "hong-dat" } });
        assert.equal((await request(`/products?artisanId=${product.artisanId}`)).json.data.every((p) => p.artisan.id === product.artisanId), true);
        const artisanProfile = await prisma.artisanProfile.findUniqueOrThrow({ where: { id: product.artisanId }, include: { user: true } });
        const artisanLogin = await request("/auth/login", { method: "POST", body: { email: artisanProfile.user.email, password: process.env.SEED_DEMO_PASSWORD } });
        assert.equal(artisanLogin.status, 200);
        const artisanToken = artisanLogin.json.data.accessToken;
        const bid = await request(`/wholesale/quotes/${quote.json.data.id}/bids`, { method: "POST", token: artisanToken, body: { proposedPrice: "1000", proposedCompletionDays: 5 } });
        assert.equal(bid.status, 201);
        const openQuotes = await request("/wholesale/open-quotes", { token: artisanToken });
        assert.equal(openQuotes.json.data.find((item) => item.id === quote.json.data.id).bids[0].id, bid.json.data.id);
        const buyerQuote = await request(`/wholesale/quotes/${quote.json.data.id}`, { token });
        assert.equal(buyerQuote.json.data.bids[0].artisan.workshopName, artisanProfile.workshopName);
        assert.equal((await request(`/wholesale/quotes/${quote.json.data.id}/accept`, { method: "POST", token, body: { bidIds: [bid.json.data.id] } })).status, 200);
        const adminLogin = await request("/auth/login", { method: "POST", body: { email: "admin@nhaxa.example", password: process.env.SEED_DEMO_PASSWORD } });
        assert.equal(adminLogin.status, 200);
        const pendingAllocations = await request("/wholesale/admin/quotes", { token: adminLogin.json.data.accessToken });
        assert.ok(pendingAllocations.json.data.some((item) => item.id === quote.json.data.id));
        assert.equal((await request("/wholesale/admin/quotes", { token })).status, 403);
        const allocate = () => request(`/wholesale/quotes/${quote.json.data.id}/assignments`, { method: "POST", token: adminLogin.json.data.accessToken, body: { allocations: [{ bidId: bid.json.data.id, quantity: 5 }] } });
        await prisma.user.update({ where: { id: artisanProfile.userId }, data: { isActive: false } });
        const unavailable = await allocate();
        assert.equal(unavailable.status, 409);
        assert.equal(unavailable.json.error.code, "ARTISAN_UNAVAILABLE");
        assert.equal(await prisma.orderAssignment.count({ where: { quotationRequestId: quote.json.data.id } }), 0);
        await prisma.user.update({ where: { id: artisanProfile.userId }, data: { isActive: true } });
        const allocation = await allocate();
        assert.equal(allocation.status, 201);
        const suspend = (isSuspended) => request(`/admin/artisans/${artisanProfile.id}/suspension`, { method: "PATCH", token: adminLogin.json.data.accessToken, body: { isSuspended } });
        assert.equal((await suspend(true)).status, 204);
        assert.equal((await request("/traceability/batches", { method: "POST", token: artisanToken, body: { productId: product.id, batchCode: "API-SUSPENDED-NEW", totalQuantity: 1 } })).status, 404);
        const advance = (status) => request(`/wholesale/assignments/${allocation.json.data[0].id}`, { method: "PATCH", token: artisanToken, body: { status } });
        assert.equal((await advance("IN_PRODUCTION")).status, 200);
        assert.equal((await advance("READY_FOR_DELIVERY")).json.error.code, "BATCH_QUANTITY_MISMATCH");
        const assignedBatch = { productId: product.id, orderAssignmentId: allocation.json.data[0].id, batchCode: "API-ALLOC-001", totalQuantity: 6 };
        assert.equal((await request("/traceability/batches", { method: "POST", token: artisanToken, body: assignedBatch })).status, 409);
        assignedBatch.totalQuantity = 4;
        const batch = await request("/traceability/batches", { method: "POST", token: artisanToken, body: assignedBatch });
        assert.equal(batch.status, 201);
        assert.equal((await advance("READY_FOR_DELIVERY")).json.error.code, "BATCHES_INCOMPLETE");
        for (const stage of ["UOM_TO", "MAC_CUI", "DET_LUA", "NHUOM_MAU", "CAN_LANG"]) {
            assert.equal((await request(`/traceability/batches/${batch.json.data.id}/logs`, { method: "POST", token: artisanToken, body: { stage, stageTitle: stage, description: "Completed stage" } })).status, 201);
        }
        assert.equal((await request(`/traceability/batches/${batch.json.data.id}/complete`, { method: "POST", token: artisanToken })).status, 200);
        assert.equal((await advance("READY_FOR_DELIVERY")).json.error.code, "BATCH_QUANTITY_MISMATCH");
        const extraBatch = await request("/traceability/batches", { method: "POST", token: artisanToken, body: { ...assignedBatch, batchCode: "API-ALLOC-002", totalQuantity: 1 } });
        assert.equal(extraBatch.status, 201);
        for (const stage of ["UOM_TO", "MAC_CUI", "DET_LUA", "NHUOM_MAU", "CAN_LANG"]) {
            assert.equal((await request(`/traceability/batches/${extraBatch.json.data.id}/logs`, { method: "POST", token: artisanToken, body: { stage, stageTitle: stage, description: "Completed stage" } })).status, 201);
        }
        assert.equal((await request(`/traceability/batches/${extraBatch.json.data.id}/complete`, { method: "POST", token: artisanToken })).status, 200);
        const assignmentId = allocation.json.data[0].id;
        const assignmentPage = await request("/wholesale/assignments?limit=1", { token: artisanToken });
        assert.deepEqual(assignmentPage.json.pagination, { page: 1, limit: 1, hasNext: false });
        assert.equal(assignmentPage.json.data[0].id, assignmentId);
        assert.equal(assignmentPage.json.data[0].batchedQuantity, 5);
        assert.equal(assignmentPage.json.data[0].completedQuantity, 5);
        const batchesPath = `/traceability/mine?assignmentId=${assignmentId}&limit=1&page=`;
        const newestBatch = await request(batchesPath + "1", { token: artisanToken });
        const olderBatch = await request(batchesPath + "2", { token: artisanToken });
        assert.deepEqual(newestBatch.json.pagination, { page: 1, limit: 1, hasNext: true });
        assert.equal(newestBatch.json.data[0].id, extraBatch.json.data.id);
        assert.equal(newestBatch.json.data[0]._count.logs, 5);
        assert.equal(olderBatch.json.data[0].id, batch.json.data.id);
        assert.equal(olderBatch.json.pagination.hasNext, false);
        assert.equal((await advance("READY_FOR_DELIVERY")).status, 200);
        assert.equal((await advance("COMPLETED")).status, 200);
        assert.equal((await request(`/wholesale/quotes/${quote.json.data.id}`, { token })).json.data.status, "DELIVERED");
        assert.equal((await suspend(false)).status, 204);
        const setQuantity = (quantity) => request(`/retail/cart/${product.id}`, { method: "PUT", token, body: { quantity } });
        assert.equal((await setQuantity(3)).status, 200);
        await prisma.product.update({ where: { id: product.id }, data: { stockQuantity: 1 } });
        assert.equal((await setQuantity(2)).status, 200);
        assert.equal((await setQuantity(3)).status, 409);
        await prisma.product.update({ where: { id: product.id }, data: { isPublished: false } });
        const staleCart = await request("/retail/cart", { token });
        assert.equal(staleCart.json.data[0].product.isAvailable, false);
        assert.equal(staleCart.json.data[0].quantity, 2);
        assert.equal((await setQuantity(1)).status, 200);
        await prisma.product.update({ where: { id: product.id }, data: { isPublished: true, stockQuantity: product.stockQuantity } });
        assert.equal((await request("/retail/cart", { token })).json.data[0].product.isAvailable, true);
        const checkoutBody = { recipientName: "Buyer", recipientPhone: "0901234567", shippingAddress: "Address" };
        const invalidPhone = await request("/retail/checkout", { method: "POST", token, body: { ...checkoutBody, recipientPhone: "abc" } });
        assert.equal(invalidPhone.status, 400);
        assert.equal(invalidPhone.json.error.code, "INVALID_PHONE");
        const order = await request("/retail/checkout", { method: "POST", token, body: checkoutBody });
        assert.equal(order.status, 201);
        assert.equal(order.json.data.buyerId, me.json.data.id);
        assert.equal((await request(`/retail/orders/${order.json.data.id}`, { token: artisanToken })).status, 403);
        assert.equal((await request(`/retail/orders/${order.json.data.id}`, { token: otherToken })).status, 404);
        assert.equal((await request("/reviews", { method: "POST", token, body: { targetType: "PRODUCT", productId: product.id, artisanId: product.artisanId, retailOrderId: order.json.data.id, rating: 5, comment: "Good" } })).status, 409);
        for (const status of ["CONFIRMED", "SHIPPING", "DELIVERED"]) {
            assert.equal((await request(`/retail/orders/${order.json.data.id}/status`, { method: "PATCH", token: artisanToken, body: { status, ...(status === "DELIVERED" ? { paymentCollected: true } : {}) } })).status, 200);
        }
        const reviewBody = { targetType: "PRODUCT", productId: product.id, artisanId: product.artisanId, retailOrderId: order.json.data.id, rating: 5, comment: "Good" };
        assert.equal((await request("/reviews", { method: "POST", token, body: reviewBody })).status, 201);
        assert.equal((await request("/reviews", { method: "POST", token, body: reviewBody })).status, 409);
        assert.equal((await request("/traceability/purchased/API-ALLOC-001", { token: otherToken })).status, 404);
        await prisma.product.update({ where: { id: product.id }, data: { isPublished: false } });
        assert.equal((await request("/traceability/API-ALLOC-001")).status, 404);
        const purchased = await request("/traceability/purchased/API-ALLOC-001", { token });
        assert.equal(purchased.status, 200);
        assert.equal(purchased.json.data.logs.length, 5);
        await prisma.product.update({ where: { id: product.id }, data: { isPublished: true } });
        const resetRequest = await request("/auth/password/reset/request", { method: "POST", body: { email: second.email } });
        assert.equal(resetRequest.status, 200);
        assert.ok(resetRequest.json.data.resetToken);
        const reset = { token: resetRequest.json.data.resetToken, newPassword: "Replacement-test-password-123" };
        assert.equal((await request("/auth/password/reset/confirm", { method: "POST", body: reset })).status, 200);
        assert.equal((await request("/auth/password/reset/confirm", { method: "POST", body: reset })).status, 400);
        assert.equal((await request("/auth/me", { token: otherToken })).status, 401);
        assert.equal((await request("/auth/login", { method: "POST", body: { email: second.email, password: second.password } })).status, 401);
        assert.equal((await request("/auth/login", { method: "POST", body: { email: second.email, password: reset.newPassword } })).status, 200);
        const pendingReset = await request("/auth/password/reset/request", { method: "POST", body: { email: credentials.email } });
        const changePassword = (newPassword) => request("/auth/password/change", { method: "POST", token, body: { currentPassword: credentials.password, newPassword } });
        const changes = await Promise.all([changePassword("New-buyer-test-password-123"), changePassword("Other-buyer-test-password-123")]);
        assert.equal(changes.filter(change => change.status === 200).length, 1);
        assert.ok(changes.every(change => [200, 401, 409].includes(change.status)));
        assert.equal((await request("/auth/password/reset/confirm", { method: "POST", body: { token: pendingReset.json.data.resetToken, newPassword: "Replacement-test-password-123" } })).status, 400);
        assert.equal((await request("/auth/me", { token })).status, 401);
        const newPassword = changes[0].status === 200 ? "New-buyer-test-password-123" : "Other-buyer-test-password-123";
        const renewed = await request("/auth/login", { method: "POST", body: { email: credentials.email, password: newPassword } });
        assert.equal(renewed.status, 200);
        const renewedToken = renewed.json.data.accessToken;
        assert.equal((await request("/auth/me", { token: renewedToken })).status, 200);
        await prisma.user.update({ where: { id: me.json.data.id }, data: { isActive: false } });
        assert.equal((await request("/auth/me", { token: renewedToken })).status, 401);
    } finally {
        await new Promise((resolve, reject) => server.close((err) => err ? reject(err) : resolve()));
        await prisma.$disconnect();
    }
});
